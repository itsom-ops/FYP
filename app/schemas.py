"""
Perspecta - Unified Pydantic Schemas & WebSocket Event Definitions
"""

from typing import Any, Dict, Optional, Literal
from pydantic import BaseModel, Field


# Standardized WebSocket Event Types
EventType = Literal[
    "agent_message",
    "handover",
    "belief_update",
    "sandbox_status",
    "graph_mutation",
    "memory_op",
    "consensus_round",
    "reward_step",
    "benchmark_update",
    "run_complete",
    "error"
]


class WSEvent(BaseModel):
    """
    Standardized WebSocket event envelope used across all Perspecta scenarios.
    """
    seq: int = Field(..., description="Monotonically increasing sequence number")
    ts: float = Field(..., description="Unix timestamp of the event")
    run_id: str = Field(..., description="Unique scenario execution identifier")
    simulated: bool = Field(..., description="Honesty flag: True if content is generated by mock/simulated provider")
    type: EventType = Field(..., description="Event type discriminator")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Event payload data")


class HealthResponse(BaseModel):
    """
    System health and active execution sandbox backend status.
    """
    status: str = "ok"
    active_backend: Literal["docker", "subprocess"]
    isolation: Literal["strong", "weak"]
    provider: str = "mock"
    docker_available: bool
    redis_available: bool
    chroma_available: bool


class ScenarioRunResponse(BaseModel):
    """
    Response returned when launching a new scenario execution.
    """
    run_id: str
    scenario: str
    status: str = "started"
    ws_url: str


class BenchmarkKPIs(BaseModel):
    """
    Aggregated benchmark KPIs computed from run execution logs.
    """
    total_runs: int = 0
    task_success_rate: float = 0.0  # percentage
    avg_consensus_iterations: float = 0.0
    avg_memory_redis_ms: float = 0.0
    avg_memory_chroma_ms: float = 0.0
    avg_graph_mutations: float = 0.0
    marl_sparse_episodes: float = 0.0
    marl_shaped_episodes: float = 0.0
    marl_improvement_pct: float = 0.0
    recent_runs: list = Field(default_factory=list)
